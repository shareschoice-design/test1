"""Registry of every short we made, and a duplicate guard.

python3 shorts_tool/registry.py build            -> writes shorts/registry.json + shorts/REGISTRY.md
python3 shorts_tool/registry.py check <url|id> [event text]   -> exit 1 if the DVIDS video or the same event is already used
Event key = event date (from description) + main place words, so the same rescue uploaded under several DVIDS ids is caught.
"""
import json, os, re, sys
REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MONTHS = "jan|feb|mar|apr|may|jun|jul|aug|sep|oct|nov|dec"


def vid(u):
    m = re.search(r"/video/(\d+)", str(u)); return m.group(1) if m else str(u)


def event_key(text):
    t = text.lower()
    d = re.search(rf"\b({MONTHS})[a-z]*\.?\s+(\d{{1,2}})(?:st|nd|rd|th)?(?:,?\s+(20\d\d))?", t)
    # year is often missing ("Friday, Feb. 3.") -> month-day is enough together with a shared place word
    date = f"{d.group(1)}-{int(d.group(2)):02d}" if d else ""
    STOP = {"coast", "guard", "station", "air", "the", "rescue", "rescues", "helicopter", "crew", "after", "near", "from", "with"}
    words = {w for w in re.findall(r"[a-z]{5,}", t) if w not in STOP}
    caps = re.findall(r"(?:near|off|in|at)\s+([A-Z][a-zA-Z]+(?:\s[A-Z][a-zA-Z]+)?)", text)
    return date, sorted({c.lower() for c in caps} | {w for w in words if w in {c.lower() for c in caps}})[:6]


def build():
    rows = []
    for d, status in (("footage/hd", "hd"), ("footage/dvids", "sd-archived"), ("footage/lowres", "lowres-rejected")):
        for f in sorted(os.listdir(os.path.join(REPO, d))):
            if not f.endswith(".json"): continue
            m = json.load(open(os.path.join(REPO, d, f)))
            rows.append({"footage": f[:-5], "dir": d, "dvids_id": vid(m.get("page", "")), "title": m.get("title", ""),
                         "event": event_key(m.get("title", "") + ". " + m.get("description", "")), "tier": status, "shorts": []})
    by_foot = {r["footage"]: r for r in rows}
    for f in sorted(os.listdir(os.path.join(REPO, "shorts", "specs"))):
        if not f.endswith(".json"): continue
        s = json.load(open(os.path.join(REPO, "shorts", "specs", f)))
        r = by_foot.get(s["file"])
        if r: r["shorts"].append({"name": f[:-5], "hook": s["hook"][0],
                                  "rendered": os.path.exists(os.path.join(REPO, "shorts", f[:-5], f[:-5] + ".mp4"))})
    rej = os.path.join(REPO, "shorts", "specs_rejected")
    for f in os.listdir(rej) if os.path.isdir(rej) else []:
        if f.endswith(".json"):
            s = json.load(open(os.path.join(rej, f))); r = by_foot.get(s["file"])
            if r: r["shorts"].append({"name": f[:-5], "hook": s["hook"][0], "rejected": True})
    json.dump(rows, open(os.path.join(REPO, "shorts", "registry.json"), "w"), indent=1)
    # duplicates report
    seen, dups = {}, []
    for r in rows:
        k = r["event"][0]
        if k and any(not s.get("rejected") for s in r["shorts"]):
            for o in seen.get(k, []):
                if set(o["event"][1]) & set(r["event"][1]) or not (o["event"][1] or r["event"][1]):
                    dups.append((o["footage"], r["footage"], k))
            seen.setdefault(k, []).append(r)
    md = ["# Registry – every short (auto-generated by shorts_tool/registry.py build)", "",
          "| # | short | hook | footage | DVIDS id | event date | tier | status |", "|---|---|---|---|---|---|---|---|"]
    i = 0
    for r in rows:
        for s in r["shorts"]:
            i += 1
            st = "REJECTED" if s.get("rejected") else ("rendered" if s.get("rendered") else "spec only")
            md.append(f"| {i} | {s['name']} | {s['hook']} | {r['footage']} | {r['dvids_id']} | {r['event'][0]} | {r['tier']} | {st} |")
    md += ["", "## Possible same-event duplicates", ""] + ([f"- {a} ↔ {b} ({k})" for a, b, k in dups] or ["- none"])
    open(os.path.join(REPO, "shorts", "REGISTRY.md"), "w").write("\n".join(md) + "\n")
    print(f"{i} shorts registered, {len(dups)} possible duplicate events")
    for a, b, k in dups: print("  DUP?", a, b, k)


def check(ref, text=""):
    rows = json.load(open(os.path.join(REPO, "shorts", "registry.json")))
    v = vid(ref); ek = event_key(text) if text else ("", [])
    hit = [r for r in rows if r["dvids_id"] == v] + \
          [r for r in rows if ek[0] and r["event"][0] == ek[0] and (set(r["event"][1]) & set(ek[1]))]
    for r in hit: print("ALREADY USED:", r["footage"], r["dvids_id"], r["event"], [s["name"] for s in r["shorts"]])
    sys.exit(1 if hit else 0)


if __name__ == "__main__":
    build() if sys.argv[1] == "build" else check(sys.argv[2], " ".join(sys.argv[3:]))
